// Generates supabase/migrations/20261019000005_seed_categories.sql from scripts/taxonomy.mjs
import { writeFileSync } from "node:fs";
import { EXPENSE, INCOME, slugify } from "./taxonomy.mjs";

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const parents = [];
const children = [];
let order = 0;
for (const [slug, name, icon, color, subs] of EXPENSE) {
  order += 10;
  parents.push(`(${q(slug)}, ${q(name)}, 'expense', ${q(icon)}, ${q(color)}, ${order})`);
  subs.forEach((sub, i) => {
    children.push(`(${q(`${slug}/${slugify(sub)}`)}, ${q(sub)}, 'expense', ${q(slug)}, ${(i + 1) * 10})`);
  });
}
for (const [slug, name, icon, color] of INCOME) {
  order += 10;
  parents.push(`(${q(slug)}, ${q(name)}, 'income', ${q(icon)}, ${q(color)}, ${order})`);
}

const sql = `-- =============================================================================
-- DhanDrashti · 0005 · Default (global) categories
-- GENERATED by scripts/generate-seed.mjs — edit scripts/taxonomy.mjs instead.
-- Idempotent: upserts by slug (partial unique index on system rows). Re-running
-- this migration never duplicates categories.
-- =============================================================================

insert into public.categories (slug, name, type, icon, color, is_system, user_id, sort_order)
select v.slug, v.name, v.type, v.icon, v.color, true, null, v.sort_order
from (values
  ${parents.join(",\n  ")}
) as v(slug, name, type, icon, color, sort_order)
on conflict (slug) where is_system do update
  set name = excluded.name,
      type = excluded.type,
      icon = excluded.icon,
      color = excluded.color,
      sort_order = excluded.sort_order;

insert into public.categories (slug, name, type, parent_id, is_system, user_id, sort_order)
select v.slug, v.name, v.type, p.id, true, null, v.sort_order
from (values
  ${children.join(",\n  ")}
) as v(slug, name, type, parent_slug, sort_order)
join public.categories p on p.slug = v.parent_slug and p.is_system
on conflict (slug) where is_system do update
  set name = excluded.name,
      type = excluded.type,
      parent_id = excluded.parent_id,
      sort_order = excluded.sort_order;
`;
writeFileSync(new URL("../supabase/migrations/20261019000005_seed_categories.sql", import.meta.url), sql);
console.log(`seed written: ${parents.length} parents, ${children.length} children`);
