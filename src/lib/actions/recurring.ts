"use server";

import { revalidatePath } from "next/cache";
import { z } from "zod";
import { createClient } from "@/lib/supabase/server";
import { requireUser } from "@/lib/auth/session";
import { fail, ok, GENERIC_ERROR, type ActionResult } from "@/lib/actions/result";
import { recurringSchema } from "@/lib/validation/recurring";
import { dateStringSchema, uuidSchema } from "@/lib/validation/common";
import { anchorDayFor } from "@/lib/finance/recurring";
import { fieldErrorsFrom, friendlyDbError } from "@/lib/actions/_helpers";
import type { RecurringProcessResult } from "@/lib/types/database";

const PATHS = ["/recurring", "/dashboard", "/transactions", "/notifications", "/budgets"];
function revalidate() {
  for (const p of PATHS) revalidatePath(p);
}

function toRow(d: z.output<typeof recurringSchema>) {
  return {
    account_id: d.accountId,
    to_account_id: d.transactionType === "transfer" ? d.toAccountId : null,
    category_id: d.transactionType === "transfer" ? null : d.categoryId,
    transaction_type: d.transactionType,
    amount: Number(d.amount),
    frequency: d.frequency,
    start_date: d.startDate,
    next_due_date: d.nextDueDate ?? d.startDate,
    end_date: d.endDate,
    anchor_day: anchorDayFor(d.startDate),
    merchant: d.merchant,
    note: d.note,
    payment_method: d.paymentMethod,
    posting_mode: d.postingMode,
  };
}

export async function createRecurringAction(input: unknown): Promise<ActionResult<{ id: string }>> {
  const parsed = recurringSchema.safeParse(input);
  if (!parsed.success) return fail("Please fix the highlighted fields.", fieldErrorsFrom(parsed.error));
  const user = await requireUser();
  const supabase = await createClient();
  const { data, error } = await supabase
    .from("recurring_transactions")
    .insert({ user_id: user.id, status: "active", ...toRow(parsed.data) })
    .select("id")
    .single();
  if (error || !data) return fail(friendlyDbError(error, GENERIC_ERROR));
  revalidate();
  return ok({ id: data.id }, "Schedule created. Due occurrences are generated by the scheduler or “Process due now”.");
}

export async function updateRecurringAction(id: unknown, input: unknown): Promise<ActionResult> {
  const idParsed = uuidSchema.safeParse(id);
  if (!idParsed.success) return fail("Invalid schedule.");
  const parsed = recurringSchema.safeParse(input);
  if (!parsed.success) return fail("Please fix the highlighted fields.", fieldErrorsFrom(parsed.error));
  await requireUser();
  const supabase = await createClient();
  const { data, error } = await supabase
    .from("recurring_transactions")
    .update(toRow(parsed.data))
    .eq("id", idParsed.data)
    .select("id");
  if (error) return fail(friendlyDbError(error, GENERIC_ERROR));
  if (!data || data.length === 0) return fail("Schedule not found.");
  revalidate();
  return ok(undefined, "Schedule updated.");
}

const statusSchema = z.enum(["active", "paused", "cancelled"]);

export async function setRecurringStatusAction(id: unknown, status: unknown): Promise<ActionResult> {
  const idParsed = uuidSchema.safeParse(id);
  const statusParsed = statusSchema.safeParse(status);
  if (!idParsed.success || !statusParsed.success) return fail("Invalid request.");
  await requireUser();
  const supabase = await createClient();
  const { data, error } = await supabase
    .from("recurring_transactions")
    .update({ status: statusParsed.data })
    .eq("id", idParsed.data)
    .select("id");
  if (error) return fail(friendlyDbError(error, GENERIC_ERROR));
  if (!data || data.length === 0) return fail("Schedule not found.");
  revalidate();
  const label = statusParsed.data === "active" ? "resumed" : statusParsed.data;
  return ok(undefined, `Schedule ${label}.`);
}

export async function deleteRecurringAction(id: unknown): Promise<ActionResult> {
  const idParsed = uuidSchema.safeParse(id);
  if (!idParsed.success) return fail("Invalid schedule.");
  await requireUser();
  const supabase = await createClient();
  const { data, error } = await supabase.from("recurring_transactions").delete().eq("id", idParsed.data).select("id");
  if (error) return fail(friendlyDbError(error, GENERIC_ERROR));
  if (!data || data.length === 0) return fail("Schedule not found.");
  revalidate();
  return ok(undefined, "Schedule deleted. Already-posted transactions are kept.");
}

/** User-triggered processing of the caller's own due schedules (idempotent). */
export async function processDueRecurringAction(): Promise<ActionResult<RecurringProcessResult>> {
  await requireUser();
  const supabase = await createClient();
  const { data, error } = await supabase.rpc("process_my_recurring_transactions", {});
  if (error) return fail(friendlyDbError(error, GENERIC_ERROR));
  const result = data?.[0] ?? { posted: 0, reminders: 0, completed: 0 };
  revalidate();
  return ok(result, `${result.posted} posted, ${result.reminders} reminder${result.reminders === 1 ? "" : "s"} created.`);
}

export async function confirmOccurrenceAction(occurrenceId: unknown, transactionDate?: unknown): Promise<ActionResult<{ transactionId: string }>> {
  const idParsed = uuidSchema.safeParse(occurrenceId);
  if (!idParsed.success) return fail("Invalid occurrence.");
  let date: string | undefined;
  if (transactionDate !== undefined && transactionDate !== null && transactionDate !== "") {
    const d = dateStringSchema.safeParse(transactionDate);
    if (!d.success) return fail("Enter a valid date.");
    date = d.data;
  }
  await requireUser();
  const supabase = await createClient();
  const { data, error } = await supabase.rpc("confirm_recurring_occurrence", {
    p_occurrence_id: idParsed.data,
    ...(date ? { p_transaction_date: date } : {}),
  });
  if (error || !data) return fail(friendlyDbError(error, "Could not post this occurrence."));
  revalidate();
  return ok({ transactionId: data }, "Transaction posted.");
}

export async function skipOccurrenceAction(occurrenceId: unknown): Promise<ActionResult> {
  const idParsed = uuidSchema.safeParse(occurrenceId);
  if (!idParsed.success) return fail("Invalid occurrence.");
  await requireUser();
  const supabase = await createClient();
  const { data, error } = await supabase
    .from("recurring_transaction_occurrences")
    .update({ status: "skipped" })
    .eq("id", idParsed.data)
    .eq("status", "pending")
    .select("id");
  if (error) return fail(friendlyDbError(error, GENERIC_ERROR));
  if (!data || data.length === 0) return fail("Occurrence is no longer pending.");
  revalidate();
  return ok(undefined, "Occurrence skipped.");
}
